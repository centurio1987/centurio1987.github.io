// 고장 — **토큰과 값이 같은** 리터럴을 `const` 로 끌어올린다.
//
// 위 `const-ref.tsx` 만 두면 「선언표는 살아 있고 사용처 추적만 죽은」 고장을 못 잡는다.
// 축이 참조에서 오므로 추적이 죽으면 히트가 통째로 0 이 되고, 래칫은 그것을
// 「줄었다」로 읽어 통과한다. 두 고장이 서로 다른 자리를 짚어야 한다.
//
// 값은 최소 정본 트리의 `--ink` 와 같은 표기다(D1). 여기서는 참조를 **삼항의 가지**에 둔다 —
// 템플릿(위)과 다른 형태라, 값 자리 훑기가 한쪽만 보게 되면 한쪽만 빨개진다.
const NAVY = "#20264A";

export default function Fault({ on }: { on: boolean }) {
  return <div style={{ color: on ? NAVY : "#333333" }} />;
}
